/**
 * Schedule materialisation.
 *
 * This is the server's core policy engine: given a set of eligible photos
 * and a device's policy, it produces the timestamped list of display events
 * the device should execute. The device never makes a scheduling decision;
 * it just executes what it is given.
 *
 * ## Selection
 *
 * Each gallery has a `rotation_mode`:
 *
 * - `random` picks a photo at random, weighted by `photos.weight`, and
 *   avoids repeating the photo shown immediately before it.
 * - `sequential` walks the gallery in order, wrapping around.
 *
 * ## Intervals
 *
 * The gap between two consecutive displays is drawn uniformly from the
 * gallery's `[min_interval, max_interval]` range. The reference firmware
 * uses a fixed interval, but a random interval reads far more naturally on
 * a wall frame, and it is server policy so it costs the device nothing.
 *
 * ## Determinism
 *
 * The result for a given (device, window start, state) must be identical on
 * every call, because a device that retries `/sync` must receive the same
 * schedule it received the first time. We therefore derive the random
 * sequence from a seeded PRNG keyed on the device id and the window start,
 * not from wall-clock entropy.
 *
 * The seed deliberately does *not* include the current time, so two syncs
 * inside the same window produce the same events.
 */

import { createHash } from "node:crypto";

/** A photo eligible for scheduling. */
export interface Candidate {
  /** Stable identifier of the source photo. */
  readonly photoId: number;
  /** Content hash of the rendered asset; this is what the device downloads. */
  readonly contentHash: string;
  /** Relative selection weight. */
  readonly weight: number;
  /** The gallery this photo belongs to. */
  readonly belongsTo: number;
}

/** A gallery's scheduling policy. */
export interface GalleryPolicy {
  readonly galleryId: number;
  readonly rotationMode: "random" | "sequential";
  readonly minInterval: number;
  readonly maxInterval: number;
}

/** A device's sync and quiet-hours policy. */
export interface DevicePolicy {
  readonly syncInterval: number;
  readonly lookahead: number;
  readonly quietStart: number | null;
  readonly quietEnd: number | null;
  readonly timezone: string;
}

/** One scheduled display event. */
export interface DisplayEvent {
  /** Epoch milliseconds at which the asset should be shown. */
  readonly at: number;
  /** Content hash of the asset to display. */
  readonly asset: string;
}

/**
 * A deterministic pseudo-random number generator.
 *
 * xoshiro128** seeded from a hash. We use this rather than `Math.random` so
 * that a schedule can be regenerated byte-for-byte.
 *
 * Exported so the tests can drive it directly.
 */
export class Rng {
  private s0: number;
  private s1: number;
  private s2: number;
  private s3: number;

  constructor(seed: Buffer) {
    // Expand the seed into four 32-bit words.
    const expanded = createHash("sha256").update(seed).digest();
    this.s0 = expanded.readUInt32LE(0);
    this.s1 = expanded.readUInt32LE(4);
    this.s2 = expanded.readUInt32LE(8);
    this.s3 = expanded.readUInt32LE(12);
    // xoshiro requires a non-zero state.
    if ((this.s0 | this.s1 | this.s2 | this.s3) === 0) this.s0 = 1;
  }

  next(): number {
    const result = (Math.imul(this.s1 * 5, 1) >>> 0);
    const rotated = (((result << 7) | (result >>> 25)) >>> 0) * 9;
    const t = (this.s1 << 9) >>> 0;

    this.s2 ^= this.s0;
    this.s3 ^= this.s1;
    this.s1 ^= this.s2;
    this.s0 ^= this.s3;
    this.s2 ^= t;
    this.s3 = ((this.s3 << 11) | (this.s3 >>> 21)) >>> 0;

    return rotated >>> 0;
  }

  /** Uniform integer in `[0, bound)`. */
  below(bound: number): number {
    if (bound <= 0) return 0;
    return this.next() % bound;
  }

  /** Uniform float in `[0, 1)`. */
  float(): number {
    return this.next() / 0x1_0000_0000;
  }
}

/**
 * Derive the seed for a materialisation.
 *
 * The seed depends on the device alone, so that a frame has one endless
 * stream of intervals and photos. A plan is then just the start of that
 * stream: the part of it that has been planned so far. When more is needed,
 * the stream is continued rather than started again, so the times and the
 * photos already in the plan keep their places and new ones follow on.
 *
 * The stream is therefore the same for a frame however many times it is
 * planned, and the plan can be rebuilt byte-for-byte.
 */
function seedFor(deviceId: string): Buffer {
  return createHash("sha256").update(`${deviceId}`).digest();
}

/**
 * Pick a photo using weighted random selection.
 *
 * A photo with weight 0 is never selected: it is excluded from the pool
 * outright rather than merely having zero probability, because the fallback
 * path (when every candidate is excluded) would otherwise hand it back.
 *
 * @param candidates  Photos eligible right now.
 * @param rng         Seeded random source.
 * @param avoid      Photo id to avoid repeating, if any.
 */
export function pickWeighted(
  candidates: readonly Candidate[],
  rng: Rng,
  avoid?: number,
): Candidate | undefined {
  // Zero-weight photos are ineligible, full stop.
  const weighted = candidates.filter((c) => c.weight > 0);
  if (weighted.length === 0) return undefined;

  const eligible = avoid === undefined ? weighted : weighted.filter((c) => c.photoId !== avoid);
  // If exclusion empties the pool, fall back to the weighted set; the
  // zero-weight photos are still not eligible.
  const pool = eligible.length > 0 ? eligible : weighted;

  const total = pool.reduce((sum, c) => sum + c.weight, 0);
  if (total <= 0) {
    return pool[rng.below(pool.length)];
  }

  let threshold = rng.float() * total;
  for (const candidate of pool) {
    threshold -= candidate.weight;
    if (threshold <= 0) return candidate;
  }
  return pool[pool.length - 1];
}

/**
 * Whether a moment falls inside a quiet-hours window.
 *
 * Quiet hours are expressed in minutes from local midnight. A window that
 * wraps past midnight (e.g. 22:00-07:00) is handled.
 */
export function inQuietHours(
  epochMs: number,
  quietStart: number | null,
  quietEnd: number | null,
  timezone = "UTC",
): boolean {
  if (quietStart === null || quietEnd === null) return false;
  if (quietStart === quietEnd) return false;

  const minute = localMinuteOfDay(epochMs, timezone);
  if (quietStart < quietEnd) {
    return minute >= quietStart && minute < quietEnd;
  }
  // Wraps midnight.
  return minute >= quietStart || minute < quietEnd;
}

/**
 * The local minute-of-day for a timestamp.
 *
 * We use the device's timezone via `Intl`, which keeps the server free of a
 * timezone database dependency.
 */
export function localMinuteOfDay(epochMs: number, timezone = "UTC"): number {
  const formatter = new Intl.DateTimeFormat("en-US", {
    timeZone: timezone,
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  });
  const parts = formatter.formatToParts(new Date(epochMs));
  const hour = Number(parts.find((p) => p.type === "hour")?.value ?? "0");
  const minute = Number(parts.find((p) => p.type === "minute")?.value ?? "0");
  return (hour % 24) * 60 + minute;
}

export interface MaterializeInput {
  readonly deviceId: string;
  /**
   * Where the plan starts.
   *
   * The first event is placed at this moment, so that a frame which has
   * just woken and has nothing cached still gets an image to show.
   */
  readonly windowStart: number;
  /**
   * The end of the window the events are planned for.
   *
   * This is not always the same as the lookahead: a frame that sleeps for
   * a long stretch has to be given a plan that reaches through the sleep,
   * or it wakes to find that its schedule has run out.
   */
  readonly windowEnd?: number;
  /**
   * The plan the frame already has, if it has one.
   *
   * The events in it keep their times and their photos. The new events are
   * added after them, so the plan grows rather than being replaced, and
   * the frame is never told that a time it is working to has moved.
   */
  readonly existing?: readonly DisplayEvent[];
  readonly candidates: readonly Candidate[];
  readonly galleries: readonly GalleryPolicy[];
  readonly policy: DevicePolicy;
  /** The asset currently on the panel, so we can avoid an immediate repeat. */
  readonly currentAsset?: string;
  /** The most recently displayed photo id, to avoid an immediate repeat. */
  readonly lastPhotoId?: number;
  /**
   * A picture pinned to a particular moment.
   *
   * A picture that arrived from a chat is pinned to the frame's next
   * check-in, so that it is shown on the next wake rather than waiting
   * for its turn in the rotation. It takes the place of whatever would
   * have been shown at that moment.
   */
  readonly pinned?: { readonly at: number; readonly contentHash: string };
}

/**
 * Materialise the display events for a window.
 *
 * The events are generated forward from the start of the plan; the first
 * event is placed at the start itself so that a device which has just
 * woken and has nothing cached still gets an image to show.
 *
 * When the frame already has a plan, the stream is continued from it. The
 * intervals and the photos in the existing plan keep their places, and the
 * new events follow on after them.
 *
 * Events falling inside quiet hours are skipped entirely: the panel keeps
 * whatever it is already showing, which needs no refresh.
 */
export function materializeSchedule(input: MaterializeInput): DisplayEvent[] {
  const { deviceId, windowStart, candidates, galleries, policy } = input;
  if (candidates.length === 0 || galleries.length === 0) return [];

  const rng = new Rng(seedFor(deviceId));
  const windowEnd = input.windowEnd ?? windowStart + policy.lookahead * 1000;

  const events: DisplayEvent[] = [];

  /* The first event is placed at the window start, so that a device which
   * has just woken and has nothing cached still gets an image to show.
   *
   * The window start is aligned to the span, so it may be a little in the
   * past by the time the device asks. An event in the past is one the
   * device will never show, and the device is only told about the events
   * that are still to come. */
  let cursor = windowStart;
  let lastPhotoId = input.lastPhotoId;
  let currentAsset = input.currentAsset;

  /* The plan the frame already has.
   *
   * The events in it were made from this same stream, so replaying the
   * stream reproduces them: the same intervals and the same photos, in
   * the same order. The replay is run over them, and the events that
   * follow are the new ones.
   *
   * While replaying, the photo that was chosen is taken from the plan
   * rather than being chosen again, so that the stream stays in step.
   *
   * The plan holds the times the events are shown at, which are rounded
   * down to the minute. The cursor is the exact time the event falls at,
   * so the lookup is by the rounded time. */
  const existing = input.existing ?? [];
  const existingByAt = new Map(existing.map((e) => [floorToMinute(e.at), e]));

  /* A picture pinned to a moment is shown at that moment.
   *
   * It does not take the place of a slot in the rotation: the pin is at
   * a moment of its own, and the frame is asleep until then. Taking a
   * slot instead would push the picture as far as a whole interval
   * later, which is the very delay the pin exists to avoid. */
  const pinned = input.pinned;

  /* The pin is an event of its own, and it may fall between two ordinary
   * slots, so it is placed at its own moment.
   *
   * A plan that already has an event at that moment keeps it: the pin was
   * made for that moment, and the event already there is the one that was
   * planned for it. Adding the pin as well would leave the frame changing
   * twice at the same instant. */
  const pinnedAt = pinned?.at;
  const pinnedAlreadyThere =
    pinnedAt !== undefined && existingByAt.has(pinnedAt);

  if (
    pinned !== undefined &&
    !pinnedAlreadyThere &&
    pinned.at >= windowStart &&
    pinned.at < windowEnd
  ) {
    events.push({ at: pinned.at, asset: pinned.contentHash });
  }

  // Guard against a pathological policy producing an unbounded loop.
  const maxEvents = 10_000;

  while (cursor < windowEnd && events.length < maxEvents) {
    const gallery = galleries[rng.below(galleries.length)]!;

    /* Choose the interval for the *next* display, so the first event lands
     * at the window start and subsequent ones are spaced out.
     *
     * The interval is the gallery's own: how often the owner wants the
     * picture to change. It has nothing to do with how often the frame
     * checks in with the server. The frame wakes for whichever comes
     * first, so a picture that falls between two check-ins is still shown
     * on time: the frame wakes for it, shows it, and goes back to sleep
     * until the check-in. */
    const span = Math.max(0, gallery.maxInterval - gallery.minInterval);
    const intervalSeconds = gallery.minInterval + (span > 0 ? rng.below(span + 1) : 0);

    /* An event the plan already has keeps its photo, so that the replay
     * stays in step with the plan and the events that follow carry on
     * from where the plan left off. */
    const already = existingByAt.get(floorToMinute(cursor));

    // Select a photo from this gallery's pool.
    const pool = candidates.filter((c) => c.belongsTo === gallery.galleryId);
    const usable = pool.length > 0 ? pool : candidates;

    let picked: Candidate | undefined;
    if (already) {
      picked = candidates.find((c) => c.contentHash === already.asset);
    } else if (gallery.rotationMode === "sequential") {
      picked = pickSequential(usable, lastPhotoId, currentAsset);
    } else {
      picked = pickWeighted(usable, rng, lastPhotoId);
    }
    // No eligible photo (e.g. every photo in the gallery has weight 0).
    // Skip this slot rather than showing something ineligible.
    if (!picked) {
      cursor += Math.max(1, intervalSeconds) * 1000;
      continue;
    }

    // Quiet hours suppress the display but not the cursor: the next event
    // is still scheduled at a sensible time.
    if (!inQuietHours(cursor, policy.quietStart, policy.quietEnd, policy.timezone)) {
      /* The event is shown on the minute it falls in, and never before the
       * window it belongs to. */
      const at = Math.max(windowStart, floorToMinute(cursor));

      /* The ordinary slot is skipped when the pinned picture is shown at
       * this very moment, so that the frame does not change twice in the
       * same instant. */
      if (!events.some((e) => e.at === at)) {
        events.push({ at, asset: picked.contentHash });
        lastPhotoId = picked.photoId;
        currentAsset = picked.contentHash;
      }
    }

    cursor += Math.max(1, intervalSeconds) * 1000;
  }

  /* The pin may fall before the window's first slot, so the events are
   * put back in order. */
  events.sort((a, b) => a.at - b.at);

  return events;
}

/**
 * Round a moment down to the minute it falls in.
 *
 * A photo that is due at twenty past half past six is shown at half past
 * six, not at some point during it. The times in the plan are what the
 * owner sees, and a time of twenty twenty-nine fifty-eight reads as
 * twenty twenty-nine even though it is nearer half past, which is
 * misleading.
 */
function floorToMinute(epochMs: number): number {
  return Math.floor(epochMs / 60_000) * 60_000;
}

/**
 * Pick the next photo in gallery order, wrapping around and skipping the
 * one shown immediately before.
 *
 * Zero-weight photos are ineligible here too, matching `pickWeighted`.
 */
function pickSequential(
  candidates: readonly Candidate[],
  lastPhotoId: number | undefined,
  currentAsset: string | undefined,
): Candidate | undefined {
  const eligible = candidates.filter((c) => c.weight > 0);
  if (eligible.length === 0) return undefined;
  if (eligible.length === 1) return eligible[0];

  const lastIndex = lastPhotoId === undefined
    ? -1
    : eligible.findIndex((c) => c.photoId === lastPhotoId);
  if (lastIndex === -1) return eligible[0];

  // Wrap around, and if that lands on the same photo (only possible with a
  // single candidate, handled above) step once more.
  let index = (lastIndex + 1) % eligible.length;
  if (eligible[index]!.contentHash === currentAsset && eligible.length > 1) {
    index = (index + 1) % eligible.length;
  }
  return eligible[index];
}
